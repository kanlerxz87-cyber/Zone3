#!/usr/bin/env python3
"""Builds the measurement layer: the outbound-click counter and the measurement desk.

    python3 tools/build_analytics.py            # write assets/analytics.js + analytics/index.html
    python3 tools/build_analytics.py --check    # exit 1 if either file is out of date

Inputs (registers, edited by hand):
    data/analytics/events.json   the five measured events, the privacy rules, the endpoint contract
    data/analytics/config.json   the runtime configuration the client is built from
    data/analytics/ledger.json   the measurement ledger (empty by design)

Outputs (generated, never edited by hand):
    assets/analytics.js          the privacy-preserving counter
    analytics/index.html         the measurement desk that documents it

The client records only what a reader did. It sets no cookie, creates no identifier, sends
nothing while the endpoint is unset, and talks to one owner-controlled endpoint when it is set.
The rules it must keep are written down in data/analytics/events.json (R1-R5) and are published
on the page the generator writes.
"""
