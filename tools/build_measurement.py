#!/usr/bin/env python3
"""Build the measurement page and the browser config from data/shop/measurement.json (build 38650305).

Writes:
  assets/measure-config.js   window.Z3_MEASURE = {enabled, endpoint}   (read by assets/measure.js)
  measurement/index.html     the reader-facing account of what is counted, and that counting is off

Usage:
  python3 tools/build_measurement.py           # write both files
  python3 tools/build_measurement.py --check   # exit 1 if either file is stale

The publish pass (sessions/aebf0747/publish_pass.py) adds the disclosure strip and footer to the page;
tools/measure_pass.py adds the two script tags to every published page.
"""
from __future__ import annotations

import html
import json
import pathlib
import sys
from datetime import date, datetime, timezone
from urllib.parse import urlsplit

ROOT = pathlib.Path(__file__).resolve().parents[1]
CFG = ROOT / "data" / "shop" / "measurement.json"
CONFIG_JS = ROOT / "assets" / "measure-config.js"
PAGE = ROOT / "measurement" / "index.html"


def _load_mod(rel_path: str, name: str):
    import importlib.util
    spec = importlib.util.spec_from_file_location(name, ROOT / rel_path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def postprocess(text: str, rel: str) -> str:
    """Apply the same post-passes the chain runs on every page, in memory, so --check is exact."""
    pp = _load_mod("sessions/aebf0747/publish_pass.py", "publish_pass_38")
    mp = _load_mod("tools/measure_pass.py", "measure_pass_38")
    existing = {p.relative_to(ROOT).as_posix() for p in ROOT.rglob("*") if p.is_file()}
    text, _ = pp.apply(text, rel, existing)
    return mp.apply(text, rel)
CANON = "https://kanlerxz87-cyber.github.io/Zone3/measurement/"


def config_js(cfg: dict) -> str:
    enabled = cfg.get("enabled") is True
    if enabled:
        target = urlsplit(cfg.get("endpoint_url", ""))
        if (target.scheme != "https" or not target.hostname or target.username or target.password
                or target.query or target.fragment or not target.path.endswith("/collect")
                or target.hostname in {"localhost", "127.0.0.1"}):
            raise ValueError("Production collection requires a valid HTTPS /collect endpoint without credentials or query strings")
        try:
            valid_port = target.port is None or 1 <= target.port <= 65535
            verified_on = date.fromisoformat(cfg.get("deployment_verified_on", ""))
        except (TypeError, ValueError):
            raise ValueError("Production activation requires a valid port and ISO deployment verification date") from None
        if not (valid_port and verified_on <= datetime.now(timezone.utc).date()
                and cfg.get("deployment_verified") is True
                and isinstance(cfg.get("deployment_evidence"), str) and cfg["deployment_evidence"].strip()):
            raise ValueError("Production activation requires dated deployment and privacy verification evidence")
    payload = {"enabled": enabled, "endpoint": cfg.get("endpoint_url", "") if enabled else ""}
    return (
        "/* Generated by tools/build_measurement.py from data/shop/measurement.json. Do not edit. */\n"
        f"window.Z3_MEASURE = {json.dumps(payload)};\n"
    )


def li(items: list[str]) -> str:
    return "".join(f"<li>{html.escape(x)}</li>" for x in items)


def page(cfg: dict) -> str:
    events = cfg["events"]
    rows = "".join(
        "<tr>"
        f"<td><code>{html.escape(ev['name'])}</code></td>"
        f"<td>{html.escape(ev['when'])}</td>"
        f"<td>{html.escape(ev['sends'])}</td>"
        f"<td>{html.escape(ev['does_not_send'])}</td>"
        '<td><a href="https://github.com/kanlerxz87-cyber/Zone3/blob/main/assets/measure.js">Browser implementation</a></td>'
        "</tr>"
        for ev in events
    )
    sources = "".join(
        f'<li><a href="{html.escape(s["url"])}" rel="noopener">{html.escape(s["label"])}</a> '
        f'<span class="muted">(checked {html.escape(s["checked_on"])})</span></li>'
        for s in cfg["sources"]
    )
    status = "ON" if (cfg.get("enabled") and cfg.get("endpoint_url")) else "OFF"
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Measurement — what is counted on this site, and what is not</title>
<meta name="description" content="The five first-party page and click events, aggregate-only collector, privacy controls and actual production deployment status.">
<link rel="canonical" href="{CANON}">
<link rel="stylesheet" href="../assets/zone3-publication.css">
</head>
<body>
<a class="skip" href="#main">Skip to content</a>
<header class="masthead">
  <div class="wrap masthead-row">
    <a class="brand" href="../index.html">Zone3 Kitchen (working name)</a>
    <span class="tagline">Measurement</span>
  </div>
</header>
<main id="main" class="wrap">
<p class="eyebrow">Measurement · status: {status}</p>
<h1>What is counted here, and what is not</h1>
<p class="lede">The site has one outbound-click and page-event counter. Production status: <strong>{status}</strong>. {html.escape(cfg["endpoint_status"])} No authorized Associates order or commission report has been obtained. Browser events do not establish conversions.</p>

<h2>Status</h2>
<ul>
  <li><strong>Counter in the browser:</strong> built (<code>assets/measure.js</code>). Current setting: <strong>{status}</strong>.</li>
  <li><strong>Collector:</strong> built as <code>tools/analytics_endpoint.py</code> and self-tested. <strong>Not deployed in production.</strong> GitHub Pages serves static files only, and GitHub's own documentation says it logs visitor IP addresses for security. The development preview can run a real same-origin collector; preview test events are not campaign evidence.</li>
  <li><strong>Event names:</strong> {html.escape(cfg["event_definitions_status"])} Historical alternate schemas remain in the repository, but their tracker is not injected.</li>
  <li><strong>Conversions:</strong> not measured here. Orders and commissions come only from the Associates reports; the campaign ledger stays empty until those reports are entered with their dates.</li>
</ul>

<h2>The five canonical events</h2>
<div class="table-wrap"><table class="data">
<thead><tr><th scope="col">Event</th><th scope="col">When it fires</th><th scope="col">Event body includes</th><th scope="col">Not included in event body</th><th scope="col">Implementation source</th></tr></thead>
<tbody>{rows}</tbody>
</table></div>

<p class="muted">These columns describe event-body fields, not everything visible to a web server. A network connection necessarily reveals an IP address to its receiving host and can include browser headers such as User-Agent. The collector does not log or retain them; a production host and any proxy require their own logging review.</p>

<h2>Rules the counter follows</h2>
<ul>{li(cfg["browser_rules"])}</ul>
<h2>Rules the collector follows</h2>
<ul>{li(cfg["collector_rules"])}</ul>

<h2>Why no visitor-level tracking</h2>
<p>Associates Program Participation Requirement 2(b) says that under no circumstances may any sub-tag, other ID or reporting provided in connection with the Associates Program be associated with a specific end user of the site. The counter therefore stores only daily totals per page and per link, never a visitor identifier. Source: <a href="https://affiliate-program.amazon.com/help/operating/policies" rel="noopener">Associates Program Policies, Participation Requirements 2(b)</a>.</p>

<h2>Sources</h2>
<ul>{sources}</ul>

<p class="muted">Generated by <code>tools/build_measurement.py</code> from <code>data/shop/measurement.json</code>. Flags: <a href="../shop/flagged/index.html">Flagged for review</a> (M38-F-01…M38-F-04).</p>
</main>
</body>
</html>
"""


def build(check: bool) -> int:
    cfg = json.loads(CFG.read_text(encoding="utf-8"))
    wanted = {CONFIG_JS: config_js(cfg), PAGE: postprocess(page(cfg), "measurement/index.html")}
    stale = []
    for path, text in wanted.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check:
        if stale:
            print("STALE:", ", ".join(stale))
            return 1
        print("measurement build current")
        return 0
    print("wrote:", ", ".join(stale) if stale else "no changes")
    return 0


if __name__ == "__main__":
    sys.exit(build("--check" in sys.argv))
