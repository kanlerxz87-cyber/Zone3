#!/usr/bin/env python3
"""Rebase conflict resolver for session 25513d33.

COORDINATION.md is append-only and several sessions append a Part at the same
place at the same time, so every rebase onto a moving `main` conflicts there.
Resolution follows the convention the board already records (logged by sessions
`dff4acde`, `ecbfe91b` and `3d359c23`): **keep both sides in full** — `main`'s
entire board first, then this session's Part appended verbatim. Nothing from any
session is dropped.

    python3 sessions/25513d33/resolve_rebase.py

Two traps this script handles, both of which have already bitten other sessions
in this repository:

1. **The marker test must be line-anchored.** The board's own prose discusses the
   string `<<<<<<<` (it appears in several conflict logs), so a substring test
   false-positives on a clean file. Worse, when such a guard aborts, the still-
   conflicted file gets staged as-is and the markers are published.
2. **`main` may itself carry a stray, unbalanced marker line** committed by an
   earlier session (observed: `>>>>>>> d99981f (...)` with no matching
   `<<<<<<<`). Only the marker lines are stripped; every other line of main's
   board is preserved verbatim.

Any conflicted file other than COORDINATION.md is resolved with
`git checkout --ours` and then rebuilt by the project's own generator, so the
committed output stays exactly what the generator produces.
"""
from __future__ import annotations

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
MARKER = re.compile(r"^(<{7}|>{7})( |$)", re.M)
PART_MARKER = "# Part — session 25513d33 (2026-11-14)"


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args],
                          capture_output=True, text=True, check=True).stdout


def conflicted() -> list[str]:
    return [ln for ln in git("diff", "--name-only", "--diff-filter=U").splitlines() if ln]


def has_marker(text: str) -> bool:
    return bool(MARKER.search(text))


def strip_marker_lines(text: str) -> tuple[str, int]:
    lines = text.splitlines(keepends=True)
    kept = [ln for ln in lines if not MARKER.match(ln)]
    return "".join(kept), len(lines) - len(kept)


def resolve_coordination() -> None:
    base = git("show", ":2:COORDINATION.md")   # ours   = main
    mine = git("show", ":3:COORDINATION.md")   # theirs = this branch
    if PART_MARKER not in mine:
        raise SystemExit("resolve_coordination: this session's Part is not in the branch side")
    part = mine[mine.index(PART_MARKER):]
    if has_marker(part):
        raise SystemExit("resolve_coordination: this session's Part still carries conflict markers")
    base_clean, dropped = strip_marker_lines(base)
    out = base_clean.rstrip("\n") + "\n\n---\n\n" + part.lstrip("\n")
    if has_marker(out):
        raise SystemExit("resolve_coordination: the merged board still carries conflict markers")
    (ROOT / "COORDINATION.md").write_text(out, encoding="utf-8")
    print(f"COORDINATION.md: main ({len(base_clean)} bytes"
          + (f", {dropped} stray marker line(s) stripped" if dropped else "")
          + f") + this session's Part ({len(part)} bytes)")


def main() -> int:
    files = conflicted()
    if not files:
        print("nothing to resolve")
        return 0
    for name in files:
        if name == "COORDINATION.md":
            resolve_coordination()
        else:
            subprocess.run(["git", "-C", str(ROOT), "checkout", "--ours", "--", name], check=True)
            print(f"{name}: took main's side (regenerated by the project's generator afterwards)")
    for path in ROOT.rglob("*"):
        if not path.is_file() or ".git" in path.parts:
            continue
        if path.suffix in (".html", ".md", ".json", ".py", ".xml", ".txt", ".css", ".js"):
            try:
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            if has_marker(text):
                print(f"WARNING: {path.relative_to(ROOT)} carries a conflict marker")
                return 1
    print("no conflict markers in the tree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
