#!/usr/bin/env python3
"""
Zone3 — repository documentation generator.

Writes the human-readable markdown documents in the repo from the same
data/*.json files the website renders from, so the documents and the site can
never disagree.

  EXECUTIVE_SUMMARY.md   <- docs/content/executive-summary.md
  docs/VERIFICATION.md   <- data/products.json + data/sources.json
  docs/FLAGGED.md        <- data/flags.json
  docs/REQUIREMENTS.md   <- data/requirements.json + docs/content/automation-design.md

Usage:  python3 tools/gen_docs.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
DOCS = os.path.join(ROOT, "docs")
CONTENT = os.path.join(DOCS, "content")


def load(name):
    with open(os.path.join(DATA, name), "r", encoding="utf-8") as fh:
        return json.load(fh)


PRODUCTS = load("products.json")
SOURCES = load("sources.json")
FLAGS = load("flags.json")
REQS = load("requirements.json")
SRC = {s["id"]: s for s in SOURCES["sources"]}
CAPTURED = PRODUCTS["meta"]["captured"]


def srcmd(sid):
    if not sid or sid not in SRC:
        return "_no official source_"
    s = SRC[sid]
    return "[%s — %s](%s)" % (sid, s["title"], s["url"])


def cell(v):
    if v is None:
        return "*(blank — unverified)*"
    if isinstance(v, float):
        return "%0.2f" % v
    return str(v).replace("|", "\\|")


def write(path, text):
    full = os.path.join(ROOT, path)
    with open(full, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote " + path)


# ---------------------------------------------------------------- EXEC SUMMARY


def gen_exec_summary():
    with open(os.path.join(CONTENT, "executive-summary.md"), "r", encoding="utf-8") as fh:
        body = fh.read().strip()
    txt = (
        "# Executive Summary — Zone3 Amazon Affiliate Platform\n\n"
        "> This document is generated from `docs/content/executive-summary.md`, the same file that\n"
        "> renders the [Executive Summary page](executive-summary.html) on the live site, so the two\n"
        "> cannot drift apart. Generated by `tools/gen_docs.py`; edit the source file, not this one.\n\n"
        + body + "\n\n"
        "---\n\n"
        "## Where to review the detail\n\n"
        "| Page | What it covers |\n"
        "| --- | --- |\n"
        "| [Dashboard](index.html) | Product snapshot, short-link resolution, headline findings |\n"
        "| [All Products](products.html) | Every field for every product, with verification status |\n"
        "| [Comparison](comparison.html) | The three products side by side |\n"
        "| [Pricing & Reviews](analysis.html) | Pricing, review and competition analysis |\n"
        "| [Commission Model](commission.html) | Official rate table, qualifying-purchase rules, bounty events |\n"
        "| [Compliance](compliance.html) | Amazon Associates obligations, FTC disclosure, payment terms |\n"
        "| [Flagged for Review](flagged.html) | %d irregularities, %d of them blocking |\n"
        "| [Sources](sources.html) | Every official source used, and what it supports |\n"
        "| [Verification Log](verification.html) | Per-field verification status |\n"
        "| [Requirements](requirements.html) | The decomposed requirements list and delivery status |\n\n"
        "Live site: <https://kanlerxz87-cyber.github.io/Zone3/>\n"
        % (len(FLAGS["flags"]), sum(1 for f in FLAGS["flags"] if f["severity"] == "blocking"))
    )
    write("EXECUTIVE_SUMMARY.md", txt)


# ---------------------------------------------------------------- VERIFICATION


def gen_verification():
    out = []
    out.append("# Verification Log")
    out.append("")
    out.append("Every value on this site, line by line, with the official source that supports it.")
    out.append("")
    out.append("**Rule applied:** a value is shown only if it was read from a page published by Amazon or")
    out.append("the U.S. Federal Trade Commission. Anything that could not be read from such a page is left")
    out.append("blank and listed here as unverified. Nothing is inferred, interpolated or averaged, and")
    out.append("nothing comes from a third-party blog, price tracker, review aggregator or model memory.")
    out.append("")
    out.append("Data captured **%s** from amazon.com (US). Prices in USD." % CAPTURED)
    out.append("")
    out.append("Machine-readable version: [`data/products.json`](../data/products.json).")
    out.append("On the site: [Verification Log](../verification.html).")
    out.append("")

    out.append("## Sources")
    out.append("")
    out.append("| ID | Source | Publisher | Official | Last updated | Used for |")
    out.append("| --- | --- | --- | --- | --- | --- |")
    for s in SOURCES["sources"]:
        out.append("| `%s` | [%s](%s) | %s | %s | %s | %s |" % (
            s["id"], s["title"], s["url"], s["publisher"],
            "yes" if s.get("official") else "no (supplied entry point)",
            s.get("last_updated", "—"), s["used_for"].replace("|", "\\|"),
        ))
    out.append("")

    for p in PRODUCTS["products"]:
        f = p["fields"]
        out.append("## %s — %s (`%s`)" % (p["id"], f["brand_from_title"]["value"], f["asin"]["value"]))
        out.append("")
        out.append("- Supplied short link: <%s> (code `%s`)" % (p["short_link"], f["short_link_code"]["value"]))
        out.append("- Canonical Amazon page: <%s>" % f["canonical_url"]["value"])
        out.append("- Amazon listing URL: <%s>" % f["amazon_listing_url"]["value"])
        out.append("- On the site: [%s](../product-%s.html)" % (f["asin"]["value"], p["slug"]))
        out.append("")
        out.append("| Field | Value | Status | Source | Note |")
        out.append("| --- | --- | --- | --- | --- |")
        for name, fld in f.items():
            out.append("| `%s` | %s | %s | %s | %s |" % (
                name, cell(fld["value"]),
                "verified" if fld["status"] == "verified" else "**unverified**",
                srcmd(fld["source"]),
                (fld.get("note") or "—").replace("|", "\\|"),
            ))
        out.append("")

    n_all = sum(len(p["fields"]) for p in PRODUCTS["products"])
    n_v = sum(1 for p in PRODUCTS["products"] for f in p["fields"].values() if f["status"] == "verified")
    out.append("## Totals")
    out.append("")
    out.append("- %d field checks across %d products." % (n_all, len(PRODUCTS["products"])))
    out.append("- %d verified, %d left blank as unverified." % (n_v, n_all - n_v))
    out.append("")
    out.append("## What was checked, and how")
    out.append("")
    out.append("1. Each `link.amazon/<code>` short link was requested and the HTTP redirect followed to its")
    out.append("   destination on `amazon.com`. The destination ASIN was read from the resolved URL and")
    out.append("   confirmed against the product title on that page.")
    out.append("2. The first link was resolved twice, at different points in the work, and returned the same")
    out.append("   ASIN both times. That rules out a random or rotating redirect.")
    out.append("3. Amazon renders the price and rating payload of a product detail page with JavaScript, so a")
    out.append("   static read of `/dp/<ASIN>` returns the page shell but not the price. Amazon's own")
    out.append("   search-results rendering of the same ASIN at `/s?k=<ASIN>` does return price, list price,")
    out.append("   promotion badge, star rating, ratings count, the *bought in the past month* signal and the")
    out.append("   lowest alternative offer, for the one matching product. That is an official Amazon page and")
    out.append("   is cited as such.")
    out.append("4. Every internal link was checked by [`tools/check_links.py`](../tools/check_links.py), which")
    out.append("   also enforces that every row of every table marked `data-verify-source` carries a source cell.")
    out.append("")
    write("docs/VERIFICATION.md", "\n".join(out) + "\n")


# --------------------------------------------------------------------- FLAGGED


def gen_flagged():
    sev_order = {"blocking": 0, "review": 1, "info": 2}
    flags = sorted(FLAGS["flags"], key=lambda f: (sev_order.get(f["severity"], 9), f["id"]))
    counts = {}
    for f in flags:
        counts[f["severity"]] = counts.get(f["severity"], 0) + 1

    out = []
    out.append("# Flagged for Review")
    out.append("")
    out.append("%d items: **%d blocking**, **%d needing a decision**, **%d informational**." % (
        len(flags), counts.get("blocking", 0), counts.get("review", 0), counts.get("info", 0)))
    out.append("")
    out.append("**Blocking** means the item must be resolved before this site operates as a live Amazon")
    out.append("Associates property. Flagged items do not block the merge or the deploy; they are published so")
    out.append("they can be reviewed after the site is live.")
    out.append("")
    out.append("On the site: [Flagged for Review](../flagged.html). Machine-readable version:")
    out.append("[`data/flags.json`](../data/flags.json).")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| ID | Severity | Item | Source |")
    out.append("| --- | --- | --- | --- |")
    for f in flags:
        out.append("| `%s` | %s | %s | %s |" % (
            f["id"], f["severity"].upper(), f["title"].replace("|", "\\|"),
            srcmd(f["source_id"])))
    out.append("")

    out.append("## Detail")
    out.append("")
    for f in flags:
        out.append("### `%s` — %s" % (f["id"], f["title"]))
        out.append("")
        out.append("**Severity:** %s  " % f["severity"].upper())
        out.append("**Source:** %s" % srcmd(f["source_id"]))
        out.append("")
        out.append("**Detail.** %s" % f["detail"])
        out.append("")
        out.append("**Impact.** %s" % f["impact"])
        out.append("")
        out.append("**Recommended action.** %s" % f["recommended_action"])
        out.append("")
    write("docs/FLAGGED.md", "\n".join(out) + "\n")


# ----------------------------------------------------------------- REQUIREMENTS


def gen_requirements():
    out = []
    out.append("# Requirements")
    out.append("")
    out.append("The project brief, decomposed into a tracked list. R01–R21 come from the brief verbatim;")
    out.append("R22–R30 are the delivery requirements for this session.")
    out.append("")
    counts = {}
    for r in REQS["requirements"]:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    out.append("**%d implemented**, **%d partial**, **%d blocked**, out of %d." % (
        counts.get("implemented", 0), counts.get("partial", 0),
        counts.get("blocked", 0), len(REQS["requirements"])))
    out.append("")
    out.append("On the site: [Requirements](../requirements.html). Machine-readable version:")
    out.append("[`data/requirements.json`](../data/requirements.json).")
    out.append("")

    out.append("## The brief")
    out.append("")
    out.append("> %s" % REQS["meta"]["brief"])
    out.append("")

    out.append("## Matrix")
    out.append("")
    out.append("| ID | Requirement | Status | Evidence | Gap | Flags |")
    out.append("| --- | --- | --- | --- | --- | --- |")
    for r in REQS["requirements"]:
        flags = ", ".join("[%s](FLAGGED.md)" % f for f in r.get("flags", [])) or "—"
        out.append("| `%s` | %s | %s | %s | %s | %s |" % (
            r["id"], r["text"].replace("|", "\\|"), r["status"].capitalize(),
            r["evidence"].replace("|", "\\|"),
            (r.get("gap") or "—").replace("|", "\\|"),
            flags))
    out.append("")

    with open(os.path.join(CONTENT, "automation-design.md"), "r", encoding="utf-8") as fh:
        out.append(fh.read().strip())
    out.append("")
    write("docs/REQUIREMENTS.md", "\n".join(out) + "\n")


# -------------------------------------------------------------------- RESEARCH


def gen_research():
    out = []
    out.append("# Research — how the three supplied links were resolved")
    out.append("")
    out.append("The brief supplied three `link.amazon` short links. This document records how each was")
    out.append("resolved to a real Amazon product and where every subsequent value came from.")
    out.append("")
    out.append("## Resolution")
    out.append("")
    out.append("| Supplied link | Code | Length | Resolves to (ASIN) | Product | Department |")
    out.append("| --- | --- | --- | --- | --- | --- |")
    for p in PRODUCTS["products"]:
        f = p["fields"]
        out.append("| <%s> | `%s` | %d | [`%s`](%s) | %s | %s |" % (
            p["short_link"], f["short_link_code"]["value"], len(f["short_link_code"]["value"]),
            f["asin"]["value"], f["canonical_url"]["value"],
            f["brand_from_title"]["value"], f["department"]["value"],
        ))
    out.append("")
    out.append("## Two irregularities in the links themselves")
    out.append("")
    out.append("1. **The codes are not ASINs.** Each is 9 characters and mixed case. An Amazon ASIN is 10")
    out.append("   characters and does not use lowercase. They are opaque short-link slugs that happen to")
    out.append("   begin with `B0`. Recorded as [F04](FLAGGED.md).")
    out.append("2. **`link.amazon` is not a documented Amazon short domain.** The links do resolve today,")
    out.append("   but no official page was found documenting `link.amazon` as an Amazon-operated shortener;")
    out.append("   Amazon's commonly documented shortener is `amzn.to`. Recorded as [F05](FLAGGED.md).")
    out.append("")
    out.append("Both were handled the same way: the short links are used only as the provenance record of what")
    out.append("was supplied. Every product fact comes from the resolved `amazon.com` page, and every outbound")
    out.append("link on the site points at the canonical `/dp/<ASIN>` URL.")
    out.append("")
    out.append("## Stability check")
    out.append("")
    out.append("The first link was requested twice, at different points in the work. Both requests returned")
    out.append("`B0CDY277D3`. The redirect is therefore stable, not random or rotating.")
    out.append("")
    out.append("## How the values were captured")
    out.append("")
    out.append("Amazon renders the price and rating payload of a product detail page with JavaScript. A static")
    out.append("read of `/dp/<ASIN>` returns the page shell, the `<title>` and the footer, but not the price.")
    out.append("The `<title>` was still useful: it carries the full product title, the brand and the department")
    out.append("(the segment after the final colon).")
    out.append("")
    out.append("Amazon's own search-results rendering of the same ASIN at `/s?k=<ASIN>` returns, for the single")
    out.append("matching product, the current price, the list price, any per-count unit price, the promotion")
    out.append("badge, the star rating, the ratings count, the *bought in the past month* demand signal, the")
    out.append("lowest alternative offer, and the canonical listing URL. That is an official Amazon page, so")
    out.append("those values were captured from it and it is cited on every row.")
    out.append("")
    out.append("Two endpoints were tried and rejected: `/gp/aod/ajax/...` returns a 404, and `/product-reviews/")
    out.append("<ASIN>` redirects to the sign-in page. Neither yielded data, so the fields they would have")
    out.append("supplied are left blank.")
    out.append("")
    out.append("## Verified values")
    out.append("")
    out.append("| Product | Price | List | Rating | Ratings | Bought past month | Promotion | Lowest other offer |")
    out.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for p in PRODUCTS["products"]:
        g = lambda n: p["fields"][n]["value"]
        out.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            p["fields"]["brand_from_title"]["value"],
            "$%0.2f" % g("current_price"), "$%0.2f" % g("list_price"),
            "%0.1f / 5" % g("rating"), g("ratings_count_display"),
            g("demand_signal"), g("deal_badge"), "$%0.2f" % g("other_offers_low"),
        ))
    out.append("")
    out.append("Sources S1-S6 are listed with links in [VERIFICATION.md](VERIFICATION.md).")
    out.append("Full detail in [VERIFICATION.md](VERIFICATION.md).")
    out.append("")
    write("docs/RESEARCH.md", "\n".join(out) + "\n")


def main():
    gen_exec_summary()
    gen_research()
    gen_verification()
    gen_flagged()
    gen_requirements()
    return 0


if __name__ == "__main__":
    sys.exit(main())
