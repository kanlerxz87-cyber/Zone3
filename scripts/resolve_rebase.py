#!/usr/bin/env python3
"""Rebase conflict resolver for session 3d359c23.

Two files need special handling when this branch rebases onto a moving `main`:

  COORDINATION.md  the board is append-only, and two sessions append at the same
                   time. Resolution: take `main`'s entire board, then append this
                   session's Part verbatim. Nothing from either side is dropped.
  data/flags.json  the flag register is a list of objects with unique ids. Resolution:
                   parse both sides, keep every flag from both, ordered by main's
                   order first and this branch's new ids appended.

Any other conflicted file is resolved with `git checkout --ours` and then regenerated
by the project's own generator, so the committed output stays what the generator
produces.

The marker check is line-start anchored: the board's own prose contains the string
"<<<<<<<" inside a sentence about conflict markers, so a substring test would both
false-positive and, worse, let a genuinely conflicted file through.

    python3 scripts/resolve_rebase.py            # resolve the files in the index
"""
from __future__ import annotations

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MARKER = re.compile(r"^(<{7}|>{7})( |$)", re.M)
PART_MARKER = "# PART — Session `3d359c23`"


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True,
                          text=True, check=True).stdout


def conflicted() -> list[str]:
    out = git("diff", "--name-only", "--diff-filter=U")
    return [line for line in out.splitlines() if line]


def has_marker(text: str) -> bool:
    return bool(MARKER.search(text))


def resolve_coordination() -> None:
    """main's whole board, then this session's Part appended."""
    base = git("show", ":2:COORDINATION.md")          # ours  = main
    mine = git("show", ":3:COORDINATION.md")          # theirs = this branch
    if PART_MARKER not in mine:
        raise SystemExit("resolve_coordination: this session's Part is not in the branch side")
    part = mine[mine.index(PART_MARKER):]
    if has_marker(part):
        raise SystemExit("resolve_coordination: this session's Part still carries conflict markers")
    # `main` may itself carry a stray, unbalanced conflict-marker line committed by an
    # earlier session (observed: `>>>>>>> d99981f (...)` at COORDINATION.md:3554 on
    # origin/main, with no matching `<<<<<<<` and no `=======`). Such a line is a
    # leftover from that session's own resolution and carries no content. Strip only
    # the marker lines; every other line of main's board is preserved verbatim.
    base_lines = base.splitlines(keepends=True)
    kept = [ln for ln in base_lines if not MARKER.match(ln)]
    dropped = len(base_lines) - len(kept)
    base_clean = "".join(kept)
    out = base_clean.rstrip("\n") + "\n\n---\n\n" + part.lstrip("\n")
    if has_marker(out):
        raise SystemExit("resolve_coordination: the merged board still carries conflict markers")
    (ROOT / "COORDINATION.md").write_text(out, encoding="utf-8")
    print(f"COORDINATION.md: main ({len(base_clean)} bytes"
          + (f", {dropped} stray marker line(s) stripped" if dropped else "")
          + f") + this session's Part ({len(part)} bytes)")


def resolve_flags() -> None:
    """Union of both flag lists, main's order first."""
    base = json.loads(git("show", ":2:data/flags.json"))
    mine = json.loads(git("show", ":3:data/flags.json"))
    out = dict(base)
    seen = {f["id"] for f in base["flags"]}
    added = 0
    for f in mine["flags"]:
        if f["id"] in seen:
            continue
        base["flags"].append(f)
        seen.add(f["id"])
        added += 1
    base["note"] = base.get("note", "").rstrip() + (
        " 2026-11-14, session 3d359c23 (merged with the register as it stood on main): "
        f"{added} flag(s) from this session's branch added.")
    (ROOT / "data/flags.json").write_text(json.dumps(base, indent=2, ensure_ascii=False) + "\n",
                                          encoding="utf-8")
    print(f"data/flags.json: {len(base['flags'])} flags "
          f"({len(base['flags']) - added} from main + {added} from this branch)")


def main() -> int:
    files = conflicted()
    if not files:
        print("nothing to resolve")
        return 0
    for name in files:
        if name == "COORDINATION.md":
            resolve_coordination()
        elif name == "data/flags.json":
            resolve_flags()
        else:
            # Generated output: take main's side and let the generator rebuild it.
            subprocess.run(["git", "-C", str(ROOT), "checkout", "--ours", "--", name], check=True)
            print(f"{name}: took main's side (regenerated by the project's generator afterwards)")
    # final safety net: nothing in the tree may carry a conflict marker
    for path in ROOT.rglob("*"):
        if not path.is_file() or ".git" in path.parts:
            continue
        if path.suffix in (".html", ".md", ".json", ".py", ".xml", ".txt", ".css", ".js"):
            try:
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            if has_marker(text):
                print(f"WARNING: {path.relative_to(ROOT)} carries a conflict marker")
                return 1
    print("no conflict markers in the tree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
