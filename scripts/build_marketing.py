def build_comparison() -> None:
    c = DOCS["comparison"]
    header = [col["label"] for col in c["columns"]]

    def cell(p, key):
        if key == "resolved_asin":
            return f'<a href="{e(p["listing_url"])}" target="_blank" rel="noopener noreferrer">{e(p["resolved_asin"])}</a>'
        if key == "capacity":
            s = [x for x in p["verified_specs"] if x["attribute"].startswith("Capacity")]
            return e(s[0]["value"]) if s else '<span class="badge unv">Unverified</span>'
        if key == "distinguishing_feature":
            s = [x for x in p["verified_specs"] if not x["attribute"].startswith("Capacity")]
            if not s:
                return '<span class="badge unv">Unverified</span>'
            return "<br>".join(e(f'{x["attribute"].replace(", as stated in the listing title", "")}: {x["value"]}') for x in s)
        if key == "brand_as_listed":
            return f'<a href="{e(p["slug"] + ".html")}">{e(p["brand_as_listed"])}</a>'
        if key == "category_path":
            return e(p["category_path"])
        if key in BANNED:
            return ('<span class="badge unv">Unverified</span><br>'
                    f'<span class="muted" style="font-size:12px">blank by design &mdash; {e(BANNED[key])}</span>')
        return e(p.get(key) or "")

    rows = [[cell(p, col["key"]) for col in c["columns"]] for p in PRODUCTS]
    body = f"""
<p class="lead">{e(c["note"])}</p>
{base.table(header, rows)}

<h2>Why four of these columns are blank on every row</h2>
{base.table(["Column", "Why it is blank", "Rule"], [
    ["Price", "Prices are served per session and the only figures in the fetched page text belonged to carousel items for other ASINs. No stable, attributable price was obtainable.", cite("MK-C09")],
    ["Star rating", "Amazon permits star ratings on an affiliate site only when they come through the Creators API or PA API. This build holds no API credentials.", cite("MK-C10")],
    ["Review count", "Same rule as star rating.", cite("MK-C10")],
    ["Commission rate", "Amazon publishes rates by commission category. No official source states the commission category of these three ASINs, and an Air Fryers browse node is not shown anywhere official to equal the rate-card row 'Kitchen'. Not derived.", cite("MK-C06")],
])}

<h2>What the comparison does support</h2>
{base.table(["Attribute", "Product 1", "Product 2", "Product 3", "Source"], [
    ["Stated capacity"] + [e([x for x in p["verified_specs"] if x["attribute"].startswith("Capacity")][0]["value"]) for p in PRODUCTS] + [cite("MK-C04")],
    ["Basket / chamber configuration"] + [
        e([x for x in p["verified_specs"] if "configuration" in x["attribute"] or "Door" in x["attribute"] or "Basket" in x["attribute"]][0]["value"])
        if [x for x in p["verified_specs"] if "configuration" in x["attribute"] or "Door" in x["attribute"] or "Basket" in x["attribute"]] else '<span class="badge unv">Unverified</span>'
        for p in PRODUCTS] + [cite("MK-C04")],
    ["Amazon browse path"] + [e(p["category_path"].split("&gt;")[-1].strip()) for p in PRODUCTS] + [cite("MK-C05")],
])}

<h2>Standing rule</h2>
<p>Nothing here is compared against a non-Amazon retailer: Amazon bars using Program Content to
promote products offered elsewhere. {cite("MK-C12")}</p>
"""
    page("comparison.html", "Side-by-side comparison", body,
         "The three listings measured against the same attributes. Blank means unverified, not zero.",
         active="marketing/index.html")


