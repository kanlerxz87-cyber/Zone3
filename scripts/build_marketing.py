def validate() -> list[str]:
    """Fail closed: refuse to write a page that breaks a hard rule."""
    errors = []
    for p in PRODUCTS:
        for cid in p["claim_ids"]:
            if cid not in CLAIMS:
                errors.append(f'{p["id"]} references unknown claim {cid}')
        for f in BANNED:
            if p.get(f) not in (None, ""):
                errors.append(f'{p["id"]} states a banned field "{f}" ({BANNED[f]})')
    for c in DOCS["claims"]:
        ids = c.get("source_ids") or [c.get("source_id")]
        for sid in ids:
            if sid not in SOURCE_IDS:
                errors.append(f'{c["id"]} references unknown source {sid}')
        if not any(x.get("url") for x in [c]):
            errors.append(f'{c["id"]} has no official URL')
    for r in DOCS["buying_guide"]["decision_rows"]:
        if r["claim"] not in CLAIMS:
            errors.append(f'buying guide row references unknown claim {r["claim"]}')
    return errors


def check_pages() -> list[str]:
    """Structural audit of what was just written: table columns must line up,
    every page must carry the disclosure, and no page may assert a price."""
    import re

    problems = []
    for f in sorted(OUT.glob("*.html")):
        h = f.read_text(encoding="utf-8")
        if "As an Amazon Associate I earn from qualifying purchases." not in h:
            problems.append(f'{f.name}: missing exact disclosure sentence')
        if h.count("<h1>") != 1:
            problems.append(f'{f.name}: expected exactly one <h1>')
        if re.search(r"\$\s?\d", h):
            problems.append(f'{f.name}: contains a currency figure')
        for tbl in re.findall(r"<table.*?</table>", h, re.S):
            head = len(re.findall(r"<th(?:\s[^>]*)?>", tbl))
            for row in re.findall(r"<tr>(.*?)</tr>", tbl, re.S)[1:]:
                n = len(re.findall(r"<t[dh](?:\s[^>]*)?>", row))
                if n != head:
                    problems.append(f'{f.name}: row has {n} cells, header has {head}')
                    break
        for a in re.findall(r'href="(?!#|https?:)([^"]+)"', h):
            if not (OUT / a.split("#")[0]).exists() and a.split("#")[0]:
                problems.append(f'{f.name}: broken local link {a}')
    return problems


def main() -> int:
    errors = validate()
    if errors:
        print("REFUSING TO BUILD:", file=sys.stderr)
        for x in errors:
            print("  -", x, file=sys.stderr)
        return 2
    OUT.mkdir(exist_ok=True)
    build_index()
    for p in PRODUCTS:
        build_product(p)
    build_comparison()
    build_buying_guide()
    problems = check_pages()
    if problems:
        print("POST-BUILD CHECK FAILED:", file=sys.stderr)
        for x in problems:
            print("  -", x, file=sys.stderr)
        return 3
    n = 4 + len(PRODUCTS)
    print(f"built {n} marketing pages in {OUT}")
    print(f"  {len(DOCS['claims'])} sourced claims, 0 prices, 0 ratings, 0 ranks stated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
